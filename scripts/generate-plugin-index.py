#!/usr/bin/env python3
"""Resolve reviewed in-tree plugin manifests before Cargo reads dependencies."""
import json
from pathlib import Path
import re
import sys
import tomllib

root = Path(__file__).resolve().parent.parent
plugins = root / 'plugins'
crate = root / 'crates/hoh-authored-plugins'
records = []
seen = set()
for folder in sorted(plugins.iterdir() if plugins.exists() else []):
    if not folder.is_dir():
        continue
    if folder.is_symlink():
        raise SystemExit(f'plugin directory must not be a symlink: {folder}')
    manifest_path = folder / 'hoh-plugin.json'
    if not manifest_path.is_file():
        raise SystemExit(f'missing plugin manifest: {manifest_path}')
    manifest = json.loads(manifest_path.read_text())
    ident, entry = manifest.get('id'), manifest.get('entry')
    if not isinstance(ident, str) or not re.fullmatch(r'[a-z](?:[a-z0-9-]{0,62}[a-z0-9])?', ident) or ident != folder.name:
        raise SystemExit(f'invalid plugin id or directory: {folder}')
    if ident in seen:
        raise SystemExit(f'duplicate plugin id: {ident}')
    if not isinstance(entry, str) or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', entry):
        raise SystemExit(f'invalid Rust entry for {ident}')
    cargo = tomllib.loads((folder / 'Cargo.toml').read_text())
    package = cargo['package']['name']
    if package != 'hoh-plugin-' + ident:
        raise SystemExit(f'plugin {ident}: package name must be hoh-plugin-{ident}')
    seen.add(ident)
    records.append((ident, entry, package))

manifest_path = crate / 'Cargo.toml'
manifest = manifest_path.read_text()
begin = '# BEGIN GENERATED PLUGINS\n'
end = '# END GENERATED PLUGINS\n'
if manifest.count(begin) != 1 or manifest.count(end) != 1:
    raise SystemExit('generated dependency markers missing or repeated')
deps = ''.join(f'plugin_{i} = {{ package = "{package}", path = "../../plugins/{ident}" }}\n' for i, (ident, _, package) in enumerate(records))
updated = manifest[:manifest.index(begin) + len(begin)] + deps + manifest[manifest.index(end):]
lines = ['// Generated by scripts/generate-plugin-index.py; do not edit.', 'pub fn register(registry: &mut hoh_loader::PluginRegistry) {']
lines += [f'    registry.add::<plugin_{i}::{entry}>("hoh:plugin-{ident}");' for i, (ident, entry, _) in enumerate(records)]
if not records:
    lines.append('    let _ = registry;')
lines += ['}', 'pub const PLUGINS: &[(&str, &str)] = &[']
lines += [f'    ("{ident}", include_str!("../../../plugins/{ident}/hoh-plugin.json")),' for ident, _, _ in records]
lines += ['];', '']
generated = '\n'.join(lines)
for path, contents in [(manifest_path, updated), (crate / 'src/generated.rs', generated)]:
    if not path.exists() or path.read_text() != contents:
        path.write_text(contents)
print(f'Indexed {len(records)} plugin(s).')

#!/usr/bin/env python3
"""Validate in-tree plugin metadata and generate the explicit release or dev index."""
import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

RELEASE_LIST = Path("plugins/index.json")
INDEX_CRATE = Path("crates/hoh-authored-plugins")
MAX_METADATA_BYTES = 256 * 1024


def issue(code, message, file=None, line=None, hint=None):
    values = dict(code=code, message=message, file=str(file) if file else None, line=line, hint=hint)
    return {name: value for name, value in values.items() if value is not None}


def check_id(ident):
    if not isinstance(ident, str) or not re.fullmatch(r"[a-z](?:[a-z0-9-]{0,62}[a-z0-9])?", ident):
        return issue("invalid_id", "Use 1–64 lowercase letters, digits or hyphens. Start with a letter and end with a letter or digit.")
    if ident == "inventory":
        return issue("reserved_id", "The plugin ID inventory is reserved by HoH.", hint="Choose a different plugin ID.")
    return None


def read_metadata(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError("Expected a regular file.")
    with path.open("rb") as stream:
        data = stream.read(MAX_METADATA_BYTES + 1)
    if len(data) > MAX_METADATA_BYTES:
        raise ValueError("Metadata exceeds 256 KiB.")
    return data.decode("utf-8")


def reject_json_constant(value):
    raise ValueError(f"Invalid JSON constant {value}.")


def check_plugin(root, ident):
    error = check_id(ident)
    if error:
        return [error], None, None
    relative = Path("plugins") / ident
    folder = root / relative
    if folder.parent.is_symlink() or folder.is_symlink() or not folder.is_dir():
        return [issue("plugin_directory", "Expected a plugin directory without symlinks.", relative,
                      hint=f"Create the plugin with hoh plugin new {ident} or check the ID.")], None, None
    issues = []
    manifest_text = None
    entry = None
    manifest_path = relative / "hoh-plugin.json"
    try:
        manifest_text = read_metadata(root / manifest_path)
        manifest = json.loads(manifest_text, parse_constant=reject_json_constant)
        if not isinstance(manifest, dict):
            raise ValueError("Expected a JSON object.")
        if manifest.get("id") != ident:
            issues.append(issue("manifest_id", f"Set id to {ident!r} to match the plugin directory.", manifest_path))
        version = manifest.get("version")
        if not isinstance(version, str) or not version.strip():
            issues.append(issue("manifest_version", "Set a nonempty version string.", manifest_path))
        entry = manifest.get("entry")
        if not isinstance(entry, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", entry):
            issues.append(issue("manifest_entry", "Set entry to the name of the exported Rust type.", manifest_path))
        if "permissions" in manifest and not isinstance(manifest["permissions"], dict):
            issues.append(issue("manifest_permissions", "Set permissions to an object.", manifest_path))
    except (OSError, ValueError, RecursionError) as error:
        issues.append(issue("manifest_unreadable", str(error), manifest_path, getattr(error, "lineno", None)))

    cargo_path = relative / "Cargo.toml"
    package = "hoh-plugin-" + ident
    try:
        cargo = tomllib.loads(read_metadata(root / cargo_path))
        package_table = cargo.get("package")
        if not isinstance(package_table, dict) or package_table.get("name") != package:
            issues.append(issue("cargo_package_name", f"Set [package].name to {package!r}.", cargo_path))
    except (OSError, ValueError, RecursionError) as error:
        issues.append(issue("cargo_manifest_unreadable", str(error), cargo_path, getattr(error, "lineno", None)))
    return issues, manifest_text, (ident, entry, package) if not issues else None


def make_index(root, records):
    manifest_path = INDEX_CRATE / "Cargo.toml"
    manifest = (root / manifest_path).read_text(encoding="utf-8")
    begin, end = "# BEGIN GENERATED PLUGINS\n", "# END GENERATED PLUGINS\n"
    if manifest.count(begin) != 1 or manifest.count(end) != 1 or manifest.index(begin) >= manifest.index(end):
        raise ValueError("Generated dependency markers are missing, repeated or reversed.")
    dependencies = "".join(
        f'plugin_{i} = {{ package = "{package}", path = "../../plugins/{ident}" }}\n'
        for i, (ident, _, package) in enumerate(records)
    )
    updated = manifest[:manifest.index(begin) + len(begin)] + dependencies + manifest[manifest.index(end):]
    lines = [
        "// Generated by scripts/generate-plugin-index.py; do not edit.",
        "pub fn register(registry: &mut hoh_loader::PluginRegistry) {",
    ]
    for i, (ident, entry, _) in enumerate(records):
        lines.append(f'    registry.add::<plugin_{i}::{entry}>("hoh:plugin-{ident}");')
    if not records:
        lines.append("    let _ = registry;")
    lines.extend(["}", "pub const PLUGINS: &[(&str, &str)] = &["])
    for ident, _, _ in records:
        lines.append(f'    ("{ident}", include_str!("../../../plugins/{ident}/hoh-plugin.json")),')
    lines.extend(["];", ""])
    return {manifest_path: updated, INDEX_CRATE / "src/generated.rs": "\n".join(lines)}


def emit(issues, fields, as_json):
    if as_json:
        print(json.dumps(dict(formatVersion=1, ok=not issues, issues=issues, **fields)))
    elif issues:
        for diagnostic in issues:
            location = diagnostic.get("file")
            print(f"{location}: {diagnostic['message']}" if location else diagnostic["message"], file=sys.stderr)
    elif "plugins" in fields:
        print("Plugins: " + ", ".join(fields["plugins"]))
        if fields["changed"]:
            print(("Would update: " if fields["dryRun"] else "Updated: ") + ", ".join(fields["changed"]))
    else:
        print("Plugin metadata is valid.")
    return int(bool(issues))


def index(root, candidate, dry_run, as_json):
    try:
        release = json.loads(read_metadata(root / RELEASE_LIST))
        if not isinstance(release, list) or any(not isinstance(ident, str) for ident in release):
            raise ValueError("Expected an array of plugin IDs.")
        if len(release) != len(set(release)):
            raise ValueError("Duplicate plugin ID in the release list.")
    except (OSError, ValueError, RecursionError) as error:
        return emit([issue("release_list", str(error), RELEASE_LIST)], {}, as_json)

    ids = sorted(set(release) | ({candidate} if candidate is not None else set()))
    issues, records = [], []
    for ident in ids:
        diagnostics, _, record = check_plugin(root, ident)
        for diagnostic in diagnostics:
            diagnostic.setdefault("file", str(RELEASE_LIST))
            diagnostic["plugin"] = ident
        issues.extend(diagnostics)
        if record:
            records.append(record)
    if issues:
        return emit(issues, {}, as_json)

    try:
        files = make_index(root, records)
        changed = []
        for relative, content in files.items():
            path = root / relative
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                changed.append(str(relative))
        if not dry_run:
            for relative in changed:
                (root / relative).write_text(files[Path(relative)], encoding="utf-8")
    except (OSError, ValueError) as error:
        return emit([issue("index_files", str(error), INDEX_CRATE)], {}, as_json)
    return emit([], dict(plugins=ids, changed=changed, dryRun=dry_run), as_json)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    operation = parser.add_mutually_exclusive_group()
    operation.add_argument("--check", metavar="ID", help="Check one plugin's source metadata.")
    operation.add_argument("--check-id", metavar="ID", help=argparse.SUPPRESS)
    operation.add_argument("--candidate", metavar="ID", help="Add one development candidate to the release list.")
    parser.add_argument("--root", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--dry-run", action="store_true", help="Preview the index files without writing them.")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    if args.check_id is not None:
        error = check_id(args.check_id)
        return emit([error] if error else [], {}, args.json)
    root = args.root if args.root is not None else Path(__file__).resolve().parent.parent
    if args.check is not None:
        issues, text, _ = check_plugin(root, args.check)
        fields = {"manifest": text} if args.root is not None and args.json else {}
        return emit(issues, fields, args.json)
    return index(root, args.candidate, args.dry_run, args.json)


if __name__ == "__main__":
    sys.exit(main())
